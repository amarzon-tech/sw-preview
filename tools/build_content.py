import json,sys,os
HERE=os.path.dirname(os.path.abspath(__file__)); ROOT=os.path.dirname(HERE)
sys.path.insert(0,HERE)
import cards_src as S
C=json.load(open(os.environ.get('SR_CACHE', os.path.join(HERE,'sr_cache.json'))))
NA,DESC=C['na'],C['foods']
def r(x):
    if x<5: return 0
    if x<1000: return int(5*round(x/5))
    return int(25*round(x/25))
def rate(mg): return 'low' if mg<=140 else ('mod' if mg<=400 else 'high')
def prate(mg): return 'low' if mg<600 else ('mod' if mg<=1000 else 'high')
def src_of(fdc):
    return f"USDA FoodData Central (SR Legacy) FDC {fdc}: {DESC[str(fdc)][:70]}"
foods={}
out_foods=[]
for f in S.FOODS:
    d=dict(f)
    if 'combo' in d:
        raw=sum(NA[str(S.PARTS[p]['fdc'])]*S.PARTS[p]['grams']/100*q for p,q in d['combo']); d['mg']=r(raw)
        d['src']="USDA FoodData Central (SR Legacy) FDC 171325 garlic powder, FDC 170931 black pepper"
        d.pop('combo')
    elif d['fdc'] is None:
        pass
    else:
        raw=NA[str(d['fdc'])]*d['grams']/100; d['raw']=round(raw,1); d['mg']=r(raw); d['src']=src_of(d['fdc'])
    d['cat_rating']=rate(d['mg'])
    d.pop('fdc',None); d.pop('grams',None)
    foods[d['id']]=d; out_foods.append(d)
parts={}
for k,p in S.PARTS.items():
    mg=0 if p['fdc'] is None else r(NA[str(p['fdc'])]*p['grams']/100)
    parts[k]=dict(id=k,name=p['name'],emoji=p['emoji'],serving=p['serving'],mg=mg,src=("No sodium (assumed)" if p['fdc'] is None else src_of(p['fdc'])))
def item(i):
    return foods.get(i) or parts[i]
plates=[]
for p in S.PLATES:
    ps=[]
    for lab,iid,q in p['parts']:
        it=item(iid); mg=r(it['mg']*q) if q!=1 else it['mg']
        ps.append(dict(t=lab,e=it['emoji'],mg=mg,ref=iid,src=it['src'] if 'src' in it else ''))
    tot=sum(x['mg'] for x in ps)
    d=dict(id=p['id'],name=p['name'],emoji=p['emoji'],slot=p['slot'],parts=ps,mg=tot,cat_rating=prate(tot),teach=p['teach'],swap=p['swap'],smart=p['smart'],src="Sum of listed parts (USDA values above)")
    plates.append(d)
cmps=[]
for c in S.COMPARES:
    a,b=foods[c['a']],foods[c['b']]
    def o(x): return dict(name=x['name'],emoji=x['emoji'],serving=x['serving'],mg=x['mg'],ref=x['id'])
    lower='a' if a['mg']<b['mg'] else 'b'
    d=dict(id=c['id'],a=o(a),b=o(b),lower=lower,teach=c['teach'],swap=c['swap'],lvl=c['lvl'],src=a['src']+' | '+b['src'])
    for k in ('cx','hx'):
        if k in c: d[k]=c[k]
    cmps.append(d)
json.dump(dict(foods=out_foods,plates=plates,compares=cmps,parts=list(parts.values())),open(os.path.join(HERE,'content.json'),'w'),indent=1,ensure_ascii=False)
from collections import Counter
print(len(out_foods),len(plates),len(cmps),len(parts),'total cards',len(out_foods)+len(plates)+len(cmps))
print(Counter(f['cat'] for f in out_foods))
print(Counter(f['cat_rating'] for f in out_foods),Counter(p['cat_rating'] for p in plates))
for f in out_foods: print(f"{f['id']:22} {f['mg']:5} {f['cat_rating']:4} L{f['lvl']} {f['serving']}")
for p in plates: print(f"{p['id']:22} {p['mg']:5} {p['cat_rating']:4} {p['slot']} "+' | '.join(f"{x['t']}={x['mg']}" for x in p['parts']))
for c in cmps: print(c['id'],c['a']['mg'],c['b']['mg'],c['lower'])

